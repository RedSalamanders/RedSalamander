<#
.SYNOPSIS
Verify the diagnostic MSVC output paths for one analysis run.
.DESCRIPTION
Called before first-party build preparation. Validates the exact repository-local
run root, distinct binary and intermediate paths, and the absence of reparse
points. Requires PowerShell 7 and the repository's guarded path module.
.PARAMETER RunId
Analysis run directory name generated by build.ps1.
.PARAMETER OutputRoot
The evaluated MSBuild output root.
.PARAMETER OutputDirectory
The evaluated project binary directory.
.PARAMETER IntermediateDirectory
The evaluated project intermediate directory.
.OUTPUTS
A terminating error on refusal. Validation is read-only.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidatePattern('^[0-9a-f]{32}$')][string]$RunId,
    [Parameter(Mandatory)][string]$OutputRoot,
    [Parameter(Mandatory)][string]$OutputDirectory,
    [Parameter(Mandatory)][string]$IntermediateDirectory
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
Import-Module (Join-Path $PSScriptRoot 'Modules/Build/ArtifactOperationLock.psm1') -ErrorAction Stop

$relativeRoot = ".build/analysis/$RunId"
$expectedRoot = Resolve-RSGuardedRepositoryPath -RepoRoot $repoRoot -GuardedRelativeRoot $relativeRoot -Path $relativeRoot
$actualRoot = Resolve-RSGuardedRepositoryPath -RepoRoot $repoRoot -GuardedRelativeRoot $relativeRoot -Path $OutputRoot
if ($actualRoot -ine $expectedRoot) {
    throw 'The analysis output root must equal the selected run directory.'
}
$binPath = Resolve-RSGuardedRepositoryPath -RepoRoot $repoRoot -GuardedRelativeRoot $relativeRoot -Path $OutputDirectory
$objRoot = Join-Path $expectedRoot 'Intermediate'
$objPath = Resolve-RSGuardedRepositoryPath -RepoRoot $repoRoot -GuardedRelativeRoot "$relativeRoot/Intermediate" -Path $IntermediateDirectory
if ($binPath -ieq $expectedRoot -or $binPath -ieq $objRoot -or
    $binPath.StartsWith("$objRoot\", [StringComparison]::OrdinalIgnoreCase) -or $objPath -ieq $objRoot) {
    throw 'The analysis output and intermediate directories must be distinct descendants of the run root.'
}
